const GENERATED_LEVEL_REWARDS: PlayerLevelReward[] = Array.from({ length: 50 }, (_, index) => {
  const level = index + 1;
  const existing = DEFINED_PLAYER_LEVEL_REWARDS.find(reward => reward.level === level);
  if (existing) return existing;

  const crateLevel = level % 5 === 0;
  return {
    level,
    title: `Ascension Level ${level}`,
    description: `Keep ascending with Astra reserves, hero card shards, and tactical supplies for your next battle.`,
    isMilestone: false,
    isMajorMilestone: false,
    rewardType: 'BUNDLE',
    astra: 500 + level * 150,
    cardShards: 0,
    draftShards: 10 + level * 3,
    crates: crateLevel ? 1 : 0,
    crateType: crateLevel ? (level >= 35 ? 'EPIC_CRATE' : 'RARE_CRATE') : undefined,
    icon: level % 2 === 0 ? '✨' : '⚡',
  };
});

const SHARD_CATEGORIES: PlayerLevelReward['shardCategory'][] = ['rare', 'epic', 'mythic', 'hero', 'villain', 'cosmic'];

export const PLAYER_LEVEL_REWARDS: PlayerLevelReward[] = GENERATED_LEVEL_REWARDS.map(reward => ({
  ...reward,
  cardShards: 0,
  shardCategory: SHARD_CATEGORIES[(reward.level - 1) % SHARD_CATEGORIES.length],
}));

export function getPlayerLevelReward(level: number): PlayerLevelReward | undefined {
  return PLAYER_LEVEL_REWARDS.find(r => r.level === level);
}
